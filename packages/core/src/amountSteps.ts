/**
 * Сумма, меняющаяся во времени (запрос владельца 2026-08-06).
 *
 * Живой случай: «интернет 2 500 до октября, потом 4 000». Выразить это сегодня можно только двумя
 * строками — одна с датой окончания, вторая с датой начала, — и тогда человек видит в списке два
 * интернета вместо одного, история платежей рвётся пополам, а прогноз считает их независимо.
 *
 * Модель — СТУПЕНИ: базовая сумма плюс список «с такой-то даты столько-то». Три причины именно так:
 *
 * 1. Цена меняется больше одного раза. Пара полей «до какой даты» и «потом сколько» покрыла бы
 *    ровно первый случай и потребовала переделки на втором.
 * 2. Пустой список = сегодняшнее поведение, значит старые строки остаются валидными и миграция
 *    данных не нужна.
 * 3. Правило «какая сумма действует на дату» становится одной чистой функцией, и все потребители —
 *    план, мастер-сетка, прогноз — берут её у одного источника. Иначе одна и та же строка показала
 *    бы разные числа на разных экранах, а это худший вид поломки: расходятся цифры, и верить
 *    перестают обеим.
 *
 * Границы ступени включающие: «с 1 октября 4 000» человек читает как «1 октября уже 4 000».
 */

export interface AmountStep {
  /** Дата, с которой действует сумма (включительно), ISO YYYY-MM-DD. */
  readonly from: string;
  readonly amountMinor: bigint;
}

/**
 * Сумма, действующая на дату: последняя наступившая ступень, иначе базовая.
 *
 * Порядок списка не важен — важна дата. При двух ступенях на один день побеждает последняя в
 * списке: молча выбирать «какую-нибудь» нельзя, иначе цифра дня зависела бы от порядка строк в
 * базе, а он не гарантирован ничем.
 */
export function amountOn(baseMinor: bigint, steps: readonly AmountStep[], onDate: string): bigint {
  let current = baseMinor;
  let currentFrom: string | null = null;
  for (const step of steps) {
    if (step.from > onDate) continue;
    // `>=`, а не `>`: при равных датах побеждает более поздняя в списке.
    if (currentFrom === null || step.from >= currentFrom) {
      current = step.amountMinor;
      currentFrom = step.from;
    }
  }
  return current;
}

/**
 * Приводит ступени к каноническому виду: по возрастанию даты, без дублей дат и без ступеней,
 * которые ничего не меняют.
 *
 * Ступень, равная предыдущей сумме, — это не настройка, а шум: она ничего не делает, но заставляет
 * человека гадать, почему в списке лишняя строка. Схлопывание здесь, а не в интерфейсе, потому что
 * данные приходят и из импорта, и из API.
 */
export function normalizeSteps(steps: readonly AmountStep[], baseMinor?: bigint): AmountStep[] {
  const byDate = new Map<string, bigint>();
  // Проход по порядку: при равных датах побеждает последняя — то же правило, что в `amountOn`.
  for (const step of steps) byDate.set(step.from, step.amountMinor);

  const sorted = [...byDate.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([from, amountMinor]) => ({ from, amountMinor }));

  const out: AmountStep[] = [];
  let previous = baseMinor;
  for (const step of sorted) {
    if (previous !== undefined && step.amountMinor === previous) continue;
    out.push(step);
    previous = step.amountMinor;
  }
  return out;
}

/**
 * Взнос, которым долг закрывается за заданное число периодов (запрос владельца 10.08.2026:
 * «остаток 300 000, хочу закрыть к маю — посчитай платёж»).
 *
 * Обратная сторона `periodsToCover` из прогноза: там из остатка и взноса выводится срок, здесь из
 * остатка и срока — взнос. Формула одна, поэтому и живёт рядом: две реализации одного деления
 * однажды разошлись бы на копейку, и «закрою к маю» превратилось бы в «закрою в июне».
 *
 * Округление ВВЕРХ и только вверх: взнос, посчитанный вниз, оставляет хвост, и долг закрывается
 * периодом позже обещанного — то есть продукт соврал бы ровно в том, ради чего его спросили.
 */
export function paymentToClose(remainingMinor: bigint, periods: number): bigint | null {
  if (!Number.isInteger(periods) || periods <= 0) return null;
  if (remainingMinor <= 0n) return 0n;
  const per = BigInt(periods);
  const whole = remainingMinor / per;
  return remainingMinor % per === 0n ? whole : whole + 1n;
}
