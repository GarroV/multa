import { describe, expect, it } from 'vitest';
import { roundExchangeUp } from './rounding.ts';

/**
 * Округление суммы к размену (issue #49).
 *
 * Никто не идёт в обменник менять 47 813 ₽ — меняют 48 000. Неокруглённая цифра выглядит точной, но
 * пользоваться ей нельзя: человек всё равно округлит в уме, и каждый раз по-своему.
 *
 * Округляем ВВЕРХ и только вверх: вниз означало бы поменять меньше, чем нужно на обязательства, —
 * то есть тихо оставить человека без части денег там, где он их запланировал.
 */
describe('roundExchangeUp', () => {
  it('поднимает до ближайшего шага', () => {
    // 47 813,00 при шаге 1 000 → 48 000,00 (суммы в minor units, exponent 2).
    expect(roundExchangeUp(4781300n, 1000, 2)).toBe(4800000n);
  });

  it('ровную сумму не трогает', () => {
    expect(roundExchangeUp(4800000n, 1000, 2)).toBe(4800000n);
  });

  it('шаг 0 — округления нет: настройка выключена', () => {
    expect(roundExchangeUp(4781300n, 0, 2)).toBe(4781300n);
  });

  it('ноль остаётся нулём: округлять нечего', () => {
    expect(roundExchangeUp(0n, 1000, 2)).toBe(0n);
  });

  it('валюта без копеек считается своим exponent', () => {
    // JPY: exponent 0, шаг 1 000 иен → 47 813 иен поднимаются до 48 000.
    expect(roundExchangeUp(47813n, 1000, 0)).toBe(48000n);
  });

  it('валюта с тремя знаками тоже: правило одно на всех', () => {
    // BHD: exponent 3. 47,813 → шаг 10 → 50,000.
    expect(roundExchangeUp(47813n, 10, 3)).toBe(50000n);
  });

  it('отрицательное не округляется вверх до нуля: это не сумма к размену', () => {
    expect(roundExchangeUp(-100n, 1000, 2)).toBe(-100n);
  });
});
