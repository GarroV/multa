import { describe, expect, test } from 'vitest';
import { amountOn, normalizeSteps, paymentToClose, type AmountStep } from './amountSteps.ts';

/**
 * Сумма, меняющаяся во времени (запрос владельца 2026-08-06).
 *
 * Живой случай: «интернет 2 500 до октября, потом 4 000». Сегодня такое выражается только двумя
 * строками — одна с датой окончания, вторая с датой начала, — и человек видит в списке два
 * интернета вместо одного, а история платежей рвётся пополам.
 *
 * Модель — ступени: базовая сумма плюс список «с такой-то даты столько-то». Не «до какой даты» и
 * не «старая/новая», потому что цена меняется больше одного раза, и вторая правка не должна
 * требовать переделки модели.
 */

const steps: AmountStep[] = [
  { from: '2026-10-01', amountMinor: 400000n },
  { from: '2027-04-01', amountMinor: 450000n },
];

describe('amountOn', () => {
  test('до первой ступени действует базовая сумма', () => {
    expect(amountOn(250000n, steps, '2026-09-30')).toBe(250000n);
  });

  test('в день ступени действует уже новая сумма', () => {
    // Граница включающая: «с 1 октября 4 000» человек понимает как «1 октября уже 4 000».
    expect(amountOn(250000n, steps, '2026-10-01')).toBe(400000n);
  });

  test('между ступенями держится последняя наступившая', () => {
    expect(amountOn(250000n, steps, '2027-01-15')).toBe(400000n);
  });

  test('после последней ступени держится она', () => {
    expect(amountOn(250000n, steps, '2030-01-01')).toBe(450000n);
  });

  test('без ступеней сумма не меняется никогда', () => {
    expect(amountOn(250000n, [], '2030-01-01')).toBe(250000n);
  });

  test('порядок ступеней в списке не важен — важна дата', () => {
    const shuffled = [...steps].reverse();
    expect(amountOn(250000n, shuffled, '2026-10-02')).toBe(400000n);
  });

  test('две ступени на одну дату: побеждает последняя в списке, а не случайная', () => {
    /*
     * Так бывает при правке: человек добавил ступень, потом передумал и добавил ещё одну на тот же
     * день. Молча выбирать «какую-нибудь» нельзя — цифра дня зависела бы от порядка строк в базе.
     */
    const same: AmountStep[] = [
      { from: '2026-10-01', amountMinor: 400000n },
      { from: '2026-10-01', amountMinor: 500000n },
    ];
    expect(amountOn(250000n, same, '2026-10-01')).toBe(500000n);
  });
});

describe('normalizeSteps', () => {
  test('сортирует по дате и схлопывает дубли дат', () => {
    const out = normalizeSteps([
      { from: '2027-04-01', amountMinor: 450000n },
      { from: '2026-10-01', amountMinor: 400000n },
      { from: '2026-10-01', amountMinor: 500000n },
    ]);
    expect(out).toEqual([
      { from: '2026-10-01', amountMinor: 500000n },
      { from: '2027-04-01', amountMinor: 450000n },
    ]);
  });

  test('выбрасывает ступени, равные предыдущей сумме: ступень без изменения — шум', () => {
    const out = normalizeSteps(
      [
        { from: '2026-10-01', amountMinor: 400000n },
        { from: '2027-01-01', amountMinor: 400000n },
        { from: '2027-04-01', amountMinor: 450000n },
      ],
      250000n,
    );
    expect(out).toEqual([
      { from: '2026-10-01', amountMinor: 400000n },
      { from: '2027-04-01', amountMinor: 450000n },
    ]);
  });

  test('первая ступень, равная базовой сумме, тоже лишняя', () => {
    const out = normalizeSteps([{ from: '2026-10-01', amountMinor: 250000n }], 250000n);
    expect(out).toEqual([]);
  });
});

describe('paymentToClose', () => {
  test('делит остаток на число периодов', () => {
    expect(paymentToClose(120000n, 12)).toBe(10000n);
  });

  test('округляет вверх: иначе хвост уедет в лишний период', () => {
    // 100 000 за 12 периодов — 8 333,33; вниз дало бы 8 333 и остаток 4 копейки в тринадцатом.
    expect(paymentToClose(100000n, 12)).toBe(8334n);
  });

  test('ноль периодов и отрицательное число — не ответ, а отказ', () => {
    expect(paymentToClose(100000n, 0)).toBe(null);
    expect(paymentToClose(100000n, -3)).toBe(null);
    expect(paymentToClose(100000n, 1.5)).toBe(null);
  });

  test('закрытый долг не требует взноса', () => {
    expect(paymentToClose(0n, 6)).toBe(0n);
  });
});
