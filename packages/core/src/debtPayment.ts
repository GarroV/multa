import { amountOn, type AmountStep } from './amountSteps.ts';

/**
 * Платёж по долгу за период — с разбивкой по источникам дохода (запрос владельца 16.08.2026:
 * «плачу я и с аванса и с зарплаты… разные суммы»).
 *
 * До этого у долга было одно число на период, и «5 000 с аванса, 15 000 с зарплаты» выразить было
 * нечем. Ступени суммы (`amountSteps`) для этого не годятся: они меняют сумму с даты и навсегда,
 * а не чередуют её от выплаты к выплате.
 *
 * **Сумма привязана к источнику дохода, а не к номеру периода.** Считать «через одну» соблазнительно
 * и неверно: ритм меняется, источники добавляются, выплата съезжает на выходной — и такая привязка
 * начинает врать молча, без единого признака на экране.
 */

export interface DebtPaymentRule {
  /** Общая сумма на период: используется, пока разбивки нет. */
  readonly paymentMinor: bigint;
  /** Ступени «с такой-то даты столько-то» — прежний механизм, остаётся для долгов без разбивки. */
  readonly steps: readonly AmountStep[];
  /** Разбивка по источникам: сколько уходит с каждой конкретной выплаты. */
  readonly bySource: readonly { readonly sourceId: string; readonly amountMinor: bigint }[];
}

/**
 * Сколько уйдёт на долг в периоде, куда приходят выплаты `sourceIdsInPeriod`.
 *
 * Разбивка сильнее ступеней. Они отвечают на разные вопросы — «сколько с какого-то момента» против
 * «сколько с какой выплаты», — и складывать их значило бы заплатить дважды. Приоритет у разбивки:
 * она задана подробнее и явнее.
 */
export function debtPaymentForPeriod(
  rule: DebtPaymentRule,
  sourceIdsInPeriod: readonly string[],
  onDate: string,
): bigint {
  if (rule.bySource.length === 0) return amountOn(rule.paymentMinor, rule.steps, onDate);

  /*
   * Складываем по всем выплатам периода: при месячном ритме в один период попадают и аванс, и
   * зарплата. Взять только первую значило бы недоплатить половину — и человек заметил бы это
   * не в продукте, а когда банк списал больше плана.
   */
  let total = 0n;
  for (const sourceId of sourceIdsInPeriod) {
    const entry = rule.bySource.find((s) => s.sourceId === sourceId);
    if (entry) total += entry.amountMinor;
  }
  return total;
}
