import { describe, expect, it } from 'vitest';
import { toCsv } from './csv.ts';

/**
 * Экспорт в CSV (Спринт 6): человек должен уметь забрать свои данные и уйти. Формат выбран не за
 * красоту, а за то, что его открывает и Excel, и Numbers, и Google Sheets без плясок.
 *
 * Экранирование здесь — не педантизм: в заметках к тратам живут запятые и кавычки («кофе, большой»),
 * а в именах категорий — переводы строк после копипаста. Одна неэкранированная запятая сдвигает всю
 * строку на колонку, и выгрузка выглядит целой, оставаясь испорченной.
 */
describe('toCsv', () => {
  it('пишет заголовок и строки в порядке колонок', () => {
    const csv = toCsv(
      ['date', 'amount'],
      [
        { date: '2026-08-01', amount: '250.00' },
        { date: '2026-08-02', amount: '19.90' },
      ],
    );
    expect(csv).toBe('date,amount\r\n2026-08-01,250.00\r\n2026-08-02,19.90');
  });

  it('экранирует запятую, кавычку и перевод строки', () => {
    const csv = toCsv(
      ['note'],
      [{ note: 'кофе, большой' }, { note: 'счёт "на двоих"' }, { note: 'первая\nвторая' }],
    );
    expect(csv).toBe('note\r\n"кофе, большой"\r\n"счёт ""на двоих"""\r\n"первая\nвторая"');
  });

  it('пустое и отсутствующее значение — пустая ячейка, а не «undefined»', () => {
    expect(toCsv(['a', 'b'], [{ a: '', b: null }])).toBe('a,b\r\n,');
  });

  it('без строк отдаёт один заголовок: пустая выгрузка честнее пустого файла', () => {
    expect(toCsv(['a', 'b'], [])).toBe('a,b');
  });
});
