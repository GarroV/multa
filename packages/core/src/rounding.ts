/**
 * Округление суммы к размену (issue #49).
 *
 * Никто не меняет 47 813 ₽ — меняют 48 000. Неокруглённая цифра выглядит точной, но пользоваться
 * ей нельзя: человек всё равно округлит в уме, и каждый раз по-своему.
 *
 * Только вверх. Вниз означало бы поменять меньше, чем нужно на обязательства периода, — тихо
 * оставить человека без части денег ровно там, где он их запланировал.
 */

/**
 * Поднимает сумму до кратной шагу. Шаг задаётся в major units (1 000 ₽), сумма — в minor.
 *
 * `step = 0` — округления нет: настройка выключена, и это не «шаг в одну копейку», а её отсутствие.
 * Отрицательные значения возвращаются как есть: суммой к размену они быть не могут, а «округлить
 * вверх» для них означало бы приблизить к нулю — то есть исказить, а не привести в порядок.
 */
export function roundExchangeUp(minor: bigint, stepMajor: number, exponent: number): bigint {
  if (stepMajor <= 0 || minor <= 0n) return minor;
  const step = BigInt(stepMajor) * 10n ** BigInt(exponent);
  const rest = minor % step;
  return rest === 0n ? minor : minor + (step - rest);
}
