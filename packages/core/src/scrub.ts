/**
 * Очистка технических сообщений от личного перед записью в лог (Спринт 6).
 *
 * Ошибки продакшена должны быть видны — но текст ошибки и стектрейс часто склеены с данными
 * человека: `Failed to parse "Зарплата 133980"` уносит в лог его доход, а ссылка со входа в демо —
 * ключ доступа.
 *
 * Вырезаем только то, что опознаётся однозначно. Угадывать остальное вредно вдвойне: агрессивная
 * чистка съедает полезное, а мягкая создаёт ложное чувство безопасности.
 */

/** Потолок длины: лог не место для мегабайтного стектрейса, а урезание должно быть заметным. */
const MAX_LENGTH = 2000;

/** Число из шести и более цифр — это сумма в minor units, id или токен, а не номер строки. */
const LONG_NUMBER = /\d{6,}/g;
const EMAIL = /[\w.+-]+@[\w-]+\.[\w.-]+/g;
const QUERY_VALUE = /([?&][\w-]+=)[^&\s]+/g;

export function scrubPii(text: string): string {
  const cleaned = text
    .replace(EMAIL, '[email]')
    .replace(QUERY_VALUE, '$1[value]')
    .replace(LONG_NUMBER, '[number]');
  return cleaned.length > MAX_LENGTH ? `${cleaned.slice(0, MAX_LENGTH - 1)}…` : cleaned;
}
