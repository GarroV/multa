import { describe, expect, test } from 'vitest';
import { periodBounds, shiftPeriod } from './historyPeriods.ts';

/**
 * Листание периодов в истории трат (issue #137).
 *
 * Отсчёт идёт от периода выплат, а не от календарного месяца: продукт живёт от выплаты до выплаты, и
 * «прошлый месяц» здесь означал бы не то, что человек видит на «Плане». Смещение считается по длине
 * самого периода — она у всех разная (10-25 это 15 дней, 25-10 это 16).
 */
describe('границы и смещение периода', () => {
  test('границы берутся как есть: [начало, конец)', () => {
    expect(periodBounds({ startsOn: '2026-08-10', endsOn: '2026-08-25' })).toEqual({
      startsOn: '2026-08-10',
      endsOn: '2026-08-25',
    });
  });

  test('нулевое смещение оставляет период на месте', () => {
    const now = { startsOn: '2026-08-10', endsOn: '2026-08-25' };
    expect(shiftPeriod(now, 0)).toEqual(now);
  });

  test('шаг назад сдвигает на длину периода, а не на месяц', () => {
    /*
     * 15 дней длины — значит предыдущий отрезок это 26.07-10.08, а не «июль». Сдвиг на календарный
     * месяц разъехался бы с ритмом уже на второй итерации.
     */
    expect(shiftPeriod({ startsOn: '2026-08-10', endsOn: '2026-08-25' }, -1)).toEqual({
      startsOn: '2026-07-26',
      endsOn: '2026-08-10',
    });
  });

  test('несколько шагов складываются', () => {
    const two = shiftPeriod({ startsOn: '2026-08-10', endsOn: '2026-08-25' }, -2);
    expect(two).toEqual({ startsOn: '2026-07-11', endsOn: '2026-07-26' });
  });

  test('шаг вперёд возвращает туда же, откуда ушли', () => {
    const now = { startsOn: '2026-08-10', endsOn: '2026-08-25' };
    expect(shiftPeriod(shiftPeriod(now, -1), 1)).toEqual(now);
  });

  test('переход через границу месяца и года считается по дням, без сюрпризов', () => {
    expect(shiftPeriod({ startsOn: '2027-01-10', endsOn: '2027-01-25' }, -1)).toEqual({
      startsOn: '2026-12-26',
      endsOn: '2027-01-10',
    });
  });
});
