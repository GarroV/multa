import { describe, expect, test } from 'vitest';
import { categoryAmounts } from './categoryRowView.ts';

/**
 * Как показывать категорию, у которой бюджета нет (issue #139).
 *
 * Замечание владельца 19.08.2026: «что происходит с визуалом расходов?». Панель рисует все
 * категории воркспейса, и те, где бюджет не задан, выглядели как `0 / 0 | 0 RUB`. На демо таких две
 * из восьми, а в личном воркспейсе владельца — восемь из девяти: бюджет задан у одной. Экран из
 * нулей.
 *
 * Спрятать такие строки нельзя: поле ввода бюджета живёт в самой строке, и без строки бюджет не
 * задать — этот замкнутый круг уже расшивали дважды (#120 для долгов, 91b38bb для категорий в
 * мастер-таблице). Значит различаем не наличие строки, а «не задано» и «ноль»: прочерк вместо
 * нуля — то же решение, что в мастер-таблице, где `state: 'none'` рисуется прочерком.
 */
describe('суммы в строке категории', () => {
  const row = (over: Partial<Parameters<typeof categoryAmounts>[0]> = {}) =>
    categoryAmounts({ allocatedMinor: '0', spentMinor: '0', remainingMinor: '0', ...over });

  test('бюджет не задан и трат нет — прочерки, а не нули', () => {
    expect(row()).toEqual({ hasBudget: false, showFact: false, showRemaining: false });
  });

  test('бюджет задан — показываем и факт, и остаток', () => {
    expect(
      row({ allocatedMinor: '2000000', spentMinor: '300000', remainingMinor: '1700000' }),
    ).toEqual({ hasBudget: true, showFact: true, showRemaining: true });
  });

  test('бюджета нет, но трата есть — факт показываем: деньги ушли, и это важнее пустоты', () => {
    /*
     * Трата без бюджета — обычное дело: человек записал покупку в категорию, где плана не ставил.
     * Спрятать её значило бы соврать, что расхода не было; в плане такая трата уже сидит в
     * перерасходе.
     */
    expect(row({ spentMinor: '150000' })).toEqual({
      hasBudget: false,
      showFact: true,
      showRemaining: false,
    });
  });

  test('нулевой бюджет, заданный человеком явно, — это ноль, а не «не задано»', () => {
    /*
     * Разница тонкая, но существенная: `allocatedMinor: '0'` приходит и когда бюджета нет, и когда
     * каскад срезал строку в ноль при нехватке денег. Второе — настоящий ноль, и прочерк вместо
     * него скрыл бы, что строку урезали. Отличаем по `shortfallMinor`: он есть только у срезанных.
     */
    expect(row({ allocatedMinor: '0', shortfallMinor: '2000000' })).toEqual({
      hasBudget: true,
      showFact: true,
      showRemaining: true,
    });
  });
});
