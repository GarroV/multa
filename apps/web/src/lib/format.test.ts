import { describe, expect, it } from 'vitest';
import { formatDate } from './format.ts';

/**
 * Дата в интерфейсе — дд.мм, год по требованию (решение владельца 2026-08-03).
 *
 * Тест держит именно порядок частей. Ошибка здесь тише всех остальных: и «08.10», и «10.08» —
 * правдоподобные даты, поймать подмену глазами нельзя, а решения по ним принимают денежные.
 */
describe('formatDate', () => {
  it('день впереди месяца, года нет', () => {
    expect(formatDate('2026-08-10')).toBe('10.08');
  });

  it('год по требованию — двумя цифрами', () => {
    expect(formatDate('2026-08-10', { year: true })).toBe('10.08.26');
  });

  it('день и месяц остаются с ведущим нулём: колонка дат обязана быть одной ширины', () => {
    expect(formatDate('2026-01-05')).toBe('05.01');
  });

  it('метка времени режется до даты, а не ломается', () => {
    expect(formatDate('2026-12-31T23:59:59.000Z')).toBe('31.12');
  });

  it('строка не похожа на дату — возвращаем как есть, а не выдумываем', () => {
    expect(formatDate('позавчера')).toBe('позавчера');
  });
});
