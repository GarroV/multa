import { useMe } from './queries.ts';

/**
 * «Сегодня» глазами воркспейса, а не браузера (#109).
 *
 * Раньше каждый экран считал дату сам через `new Date().toISOString()` — это UTC. Сервер живёт по
 * таймзоне воркспейса, и между местной полуночью и смещением зоны они расходились на день: трата,
 * введённая в 00:48 в Белграде, уезжала во вчерашний день, а на стыке полумесяцев — в предыдущий
 * период, и цифра дня считалась не там. Семнадцать мест вычисляли дату независимо, то есть
 * ошибались все сразу и по-разному.
 *
 * Дата приходит из `/v1/me` — запрос всё равно живёт в кэше на каждом экране, лишней сети нет.
 * Фоллбэк на UTC оставлен намеренно: пока `me` не загрузился, поле даты не должно быть пустым, а
 * ошибиться на день в этот момент можно только если человек открыл приложение ровно в полночь и
 * успел записать трату до ответа сервера.
 */
export function useToday(): string {
  const { data } = useMe();
  return data?.today ?? new Date().toISOString().slice(0, 10);
}
