import { useSettings, type GridSection } from './queries.ts';

/**
 * Какие разделы показывать (решение владельца 06.08.2026, вынесено в настройки 22.08.2026).
 *
 * Скрыты по умолчанию цели и валютные корзины. Причина продуктовая, а не техническая: «цель» и
 * «корзина» — та же механика, что долг и накопление, только под другими именами, и похожие разделы
 * рядом мешают заполнять, а не помогают.
 *
 * Раньше это была константа в коде: поменять набор мог только тот, у кого есть репозиторий, — то
 * есть для пользователя настройки не существовало. Теперь она в настройках воркспейса («все
 * настройки таблицы убираем в настройки»), поэтому здесь остались дефолты на время загрузки и для
 * воркспейса без сохранённых настроек.
 *
 * Спрятано ИМЕННО в интерфейсе: ручки API, таблицы и уже заведённые строки на месте. Удалять данные
 * под живым продуктом ради упрощения экрана нельзя: вернуть их будет нечем.
 */
export const DEFAULT_SECTIONS: Record<GridSection, boolean> = {
  income: true,
  debt: true,
  bucket: false,
  envelope: true,
  category: true,
  goal: false,
  recurring: true,
  account: true,
};

/**
 * Показывать ли раздел. Один вопрос — один ответ, чтобы экраны не расходились между собой.
 *
 * Хук, а не функция: ответ зависит от настроек воркспейса, а их надо прочитать. Пока настройки
 * едут, отвечаем дефолтами — иначе первый кадр показал бы разделы, которые человек скрыл, и они
 * мигали бы при каждом открытии экрана.
 */
export function useSectionVisible(): (kind: string) => boolean {
  const { data } = useSettings();
  const sections = data?.grid.sections ?? DEFAULT_SECTIONS;
  return (kind: string) => sections[kind as GridSection] ?? true;
}
