/**
 * Разделы, скрытые из интерфейса (решение владельца 06.08.2026).
 *
 * Скрыты цели и валютные корзины. Причина продуктовая, а не техническая: «цель» и «корзина» — та
 * же механика, что долг и накопление, только под другими именами, и похожие разделы рядом мешают
 * заполнять, а не помогают.
 *
 * Счета 06.08.2026 скрывались вместе с ними и 10.08.2026 возвращены по решению владельца: раздел
 * оказался нужен, а спор был о слове «счета» (его читают как «счета к оплате»), а не о самой
 * функции.
 *
 * Спрятано ИМЕННО в интерфейсе: ручки API, таблицы и уже заведённые строки на месте. Это решение
 * обратимо одной константой — если раздел понадобится, он вернётся со своими данными, а не с нуля.
 * Удалять данные под живым продуктом ради упрощения экрана нельзя: вернуть их будет нечем.
 */
export const HIDDEN_SECTIONS = ['goal', 'bucket'] as const;

export type HiddenSection = (typeof HIDDEN_SECTIONS)[number];

/** Показывать ли раздел. Один вопрос — один ответ, чтобы экраны не расходились между собой. */
export function isSectionVisible(kind: string): boolean {
  return !(HIDDEN_SECTIONS as readonly string[]).includes(kind);
}
