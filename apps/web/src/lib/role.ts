import { useMe } from './queries.ts';

/**
 * Роль смотрящего (issue #46).
 *
 * Нужна не ради надписи, а ради того, чтобы не звать ручки, которые участнику закрыты: пока ручка
 * не умеет матрицу видимости, сервер отвечает ей 403, и панель, построенная на такой ручке, у
 * участника показывала бы «не смогли загрузить» — то есть врала бы про сбой там, где на самом деле
 * ограничение доступа.
 */
export function useIsMember(): boolean {
  const { data: me } = useMe();
  return me?.role === 'member';
}
