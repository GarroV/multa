import { useEffect, useRef } from 'react';

/**
 * Поведение модального листа: Escape закрывает, фокус возвращается туда, откуда лист открыли.
 *
 * До этого Escape не закрывал ни один лист ввода — обработчик существовал только в обучающем туре
 * (найдено сверкой 05.08.2026). Для клавиатуры это тупик: лист объявлен `aria-modal`, экранный
 * читатель обещает пользователю модальное поведение, а выйти из него можно только мышью по кнопке.
 *
 * Возврат фокуса не украшение: без него после закрытия фокус остаётся на `body`, и следующий Tab
 * начинает обход страницы с начала — человек, который вводил трату с клавиатуры, теряет место.
 *
 * Хук общий на все листы (ввод траты, чек, размен, поступление, пересборка): пять своих
 * обработчиков разошлись бы поведением при первой же правке.
 */
export function useSheet(onClose: () => void): void {
  const opener = useRef<HTMLElement | null>(null);
  /*
   * Кнопку запоминаем в теле рендера, а НЕ в эффекте. Эффекты выполняются после вставки листа в
   * DOM, а поле суммы забирает фокус на себя через autoFocus ещё в момент вставки — эффект успевал
   * записать не кнопку, а это поле, и возвращать фокус было уже некуда (проверено тестом:
   * activeElement после закрытия оставался body). Рендер идёт до вставки, там фокус ещё на кнопке.
   */
  if (opener.current === null && typeof document !== 'undefined') {
    opener.current = document.activeElement instanceof HTMLElement ? document.activeElement : null;
  }

  useEffect(() => {
    return () => {
      const back = opener.current;
      /*
       * Возврат фокуса — следующим тиком, а не сразу. В момент размонтирования лист ещё в DOM;
       * браузер удаляет узел с фокусом ПОСЛЕ нашей уборки и сбрасывает фокус на body, затирая всё,
       * что мы успели поставить. Проверено тестом: без задержки activeElement оставался body.
       */
      setTimeout(() => {
        // Кнопка могла исчезнуть вместе с перерисовкой — возвращаем фокус только если она жива.
        if (back?.isConnected) back.focus();
      }, 0);
    };
  }, []);

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.key !== 'Escape') return;
      /*
       * Нативные всплывающие списки (`<select>`, календарь `<input type="date">`) тоже закрываются
       * по Escape. Если лист закроется вместе с ними, человек потеряет введённое из-за нажатия,
       * которым хотел всего лишь свернуть выпадашку.
       */
      e.stopPropagation();
      onClose();
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [onClose]);
}
