import { describe, expect, test } from 'vitest';
import { envelopeEditFieldKind, envelopeEditFieldValue } from './envelopeView.ts';

/**
 * Конверт хранит `ruleValue` как разные по смыслу числа в зависимости от вида (issue #127):
 * у «фикс» это деньги в minor units («5000» = 50 EUR), у «процент» — просто число процента
 * («10» = 10%). Список это уже различает (`formatMinor` только для «фикс»); поле правки — нет,
 * оно всегда было `plain` вне зависимости от вида, и человек видел сырые minor units как есть
 * («5000.0000» вместо «50 EUR» — то, что владелец назвал бредом).
 *
 * Функция чистая и вынесена из компонента (правило 4: домен — не в JSX), чтобы решение
 * «какого вида поле» проверялось без рендера — и чтобы у списка и у правки был ОДИН источник
 * истины про смысл ruleValue, а не два независимых места, которые уже разошлись однажды.
 */
describe('вид поля правки суммы конверта (issue #127)', () => {
  test('фикс — поле денежное: значение конвертируется major↔minor', () => {
    /*
     * Раньше поле правки для ЛЮБОГО вида конверта было `plain`: сырое значение из БД показывалось
     * как есть («5000.0000»), и сохранение без изменений округляло его до целого («5000» minor —
     * почти правильно случайно). Но любое РЕАЛЬНОЕ изменение суммы (человек стирает «5000.0000» и
     * печатает «60», думая, что вводит 60 EUR) уходило на сервер как ruleValue="60" — 60 MINOR
     * units, то есть 0.60 EUR. Тихая потеря в 100 раз при первом же реальном использовании поля.
     */
    expect(envelopeEditFieldKind('fixed')).toBe('minor');
  });

  test('процент — поле обычное число, не деньги', () => {
    expect(envelopeEditFieldKind('percent')).toBe('plain');
  });
});

describe('значение поля правки суммы конверта', () => {
  test('фикс: numeric(12,4) из БД («5000.0000») превращается в чистое целое minor units', () => {
    /*
     * Найдено при живой проверке в браузере, а не только чтением кода: с правильным `kind: 'minor'`
     * из предыдущего теста форма правки СЛОМАЛАСЬ НАСМЕРТЬ — «Uncaught SyntaxError: Cannot convert
     * 5000.0000 to a BigInt». Колонка `envelopes.rule_value` — `numeric(12, scale: 4)`, и API отдаёт
     * её строкой как есть, с четырьмя нулями после точки. `BigInt()` десятичные строки не принимает
     * вообще — ни округляя, ни отбрасывая дробную часть, а бросая исключение. Список эту же строку
     * уже обрезает (`e.ruleValue.split('.')[0]`) — форма правки должна делать то же самое.
     */
    expect(envelopeEditFieldValue('fixed', '5000.0000')).toBe('5000');
  });

  test('фикс: целая строка без точки остаётся как есть', () => {
    expect(envelopeEditFieldValue('fixed', '5000')).toBe('5000');
  });

  test('процент: дробная часть — законная часть числа, не обрезается', () => {
    // 12.5% — обычный процент, а не деньги в minor units; отрезать «.5» значило бы исказить ввод.
    expect(envelopeEditFieldValue('percent', '12.5000')).toBe('12.5000');
  });
});
