/**
 * Свежесть прод-сборки перед браузерным прогоном (issue #146).
 *
 * E2E идёт по `vite preview` с `reuseExistingServer`: если порт уже слушают, команда
 * `pnpm build && vite preview` не выполняется вовсе — и тесты проверяют бандл, собранный когда-то
 * раньше. Ошибается это в обе стороны, и вторая хуже: сломал код, прогнал, зелено, закоммитил.
 *
 * Признака в выводе нет никакого — `reuseExistingServer` работает молча, строки `pnpm build` просто
 * не появляется, а её отсутствие не бросается в глаза, когда ждёшь итог по двум сотням тестов.
 * Поэтому решает не внимательность, а проверка.
 *
 * Живёт в `lib`, а не в скрипте: правило простое, но ошибиться в нём легко (перепутать сторону
 * сравнения, уронить прогон на первой сборке), а тестом это ловится за секунду.
 */

export interface BundleState {
  /** Время самого свежего файла сборки; `null`, если сборки ещё нет. */
  readonly distMs: number | null;
  /** Время самого свежего исходника, влияющего на сборку. */
  readonly srcMs: number;
  /** Занят ли порт preview — то есть будет ли сборка пропущена. */
  readonly portBusy: boolean;
}

/** `stale-served` означает «прогон проверит не тот код»; всё остальное — можно бежать. */
export type BundleVerdict = 'ok' | 'stale-served';

export function staleBundleVerdict({ distMs, srcMs, portBusy }: BundleState): BundleVerdict {
  // Сборки нет — её сделает сам прогон, мешать нечему.
  if (distMs === null) return 'ok';
  // Порт свободен — Playwright поднимет свой сервер и соберёт заново, устаревший dist не страшен.
  if (!portBusy) return 'ok';
  /*
   * Равенство считаем свежестью: у mtime на части файловых систем секундная гранулярность, и сборка,
   * законченная в ту же секунду, что правка, выглядела бы устаревшей. Ложный останов приучает
   * обходить проверку — это дороже пропущенного пограничного случая.
   */
  return distMs < srcMs ? 'stale-served' : 'ok';
}
