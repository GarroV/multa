/**
 * Справка под вопросительным знаком (решение владельца 11.08.2026).
 *
 * Пояснения занимали строку под каждой формой навсегда, хотя нужны один раз: человек, который уже
 * понял, что такое «Осталось», читает эту строку каждый раз, когда заводит долг. Плотный экран
 * живёт тем, что на нём нет ничего лишнего, — поэтому справка сворачивается в знак, а текст
 * показывается по наведению и по фокусу с клавиатуры.
 *
 * `title` даёт подсказку мышью, `aria-label` — экранному читателю: без второго знак «?» читался бы
 * как «вопросительный знак», то есть справка исчезла бы для тех, кому она нужнее всего.
 */
export function Hint({ text }: { text: string }) {
  return (
    <span className="hint" tabIndex={0} role="note" aria-label={text} title={text}>
      ?
    </span>
  );
}
