import { useI18n } from '../lib/i18n.tsx';
import { useOnline } from '../lib/useOnline.ts';

/**
 * Полоса «нет сети» (Спринт 6, PWA).
 *
 * Живёт выше гейта авторизации, а не внутри оболочки приложения. Причина не в удобстве: без сети
 * запрос `/v1/me` не проходит, гейт показывает лендинг или форму входа — и полоса, спрятанная в
 * оболочке, не появлялась именно тогда, когда нужна. Поймано красным CI: локально сеть отваливалась
 * уже после загрузки, на чистой машине — раньше.
 *
 * Приложение открывается из кэша, поэтому без этой полосы человек видел бы пустой экран и решил, что
 * данные потерялись.
 */
export function OfflineBar() {
  const { t } = useI18n();
  const online = useOnline();
  if (online) return null;
  return <div className="offline-bar">{t('common.offline')}</div>;
}
