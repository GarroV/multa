-- Бэкфилл period_id у транзакций, импортированных из Excel (issue #101).
--
-- Импорт вставлял строки без period_id, а категорийная аналитика джойнится ИМЕННО по нему
-- (routes/analytics.ts, innerJoin с pay_periods). Импортированная история молча выпадала из
-- отчётности: перенос отрабатывал, рапортовал об успехе, а в статистике не появлялось ничего.
--
-- Границы периода — полуинтервал [starts_on, ends_on), как везде в коде
-- (routes/transactions.ts:80-81, plan/assemble.ts:680-681). Иначе строка на стыке досталась бы
-- сразу двум периодам и удвоилась в сумме.
--
-- Ограничение, о котором нужно знать: заполняются только те строки, чей период уже
-- материализован в pay_periods. Создать недостающие периоды здесь нечем — для этого нужен ритм
-- выплат воркспейса и расчёт дохода, то есть код приложения. Такие строки заполнятся сами при
-- следующем импорте в тот же период (ensurePeriodForDate создаёт строку периода) или при открытии
-- этого периода в приложении.

UPDATE transactions AS t
SET period_id = p.id
FROM pay_periods AS p
WHERE t.period_id IS NULL
  AND p.workspace_id = t.workspace_id
  AND t.occurred_on >= p.starts_on
  AND t.occurred_on < p.ends_on;
